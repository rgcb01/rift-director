const {test,expect}=require('@playwright/test');
const base=process.env.RIFT_TEST_URL||'http://127.0.0.1:8080';
for(const width of [390,1440]){
 test('Rift Director tutorial: five progressive, real-engine lessons at '+width+'px',async({browser})=>{
  const context=await browser.newContext({viewport:{width,height:width===390?844:900},isMobile:width===390,hasTouch:width===390,reducedMotion:'reduce'});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(base+'/');
  const keysBefore=await page.evaluate(()=>Object.keys(localStorage).sort());
  await page.locator('[data-setup="tutorial"]').click();
  await expect(page.locator('.tutorial-guide')).toBeVisible();
  await expect(page.locator('.tutorial-guide')).toContainText('Explora un carril');
  await page.locator('[data-focus-lane="TOP"]').click();
  await expect(page.locator('.tutorial-guide')).toContainText('Cambia de posición');
  await page.locator('[data-unit="p0:c0"]').click();
  await page.locator('[data-order="SWAP_RANK"]').click();
  await expect(page.locator('.tutorial-done')).toContainText('Conoce la Convergencia');
  await page.locator('[data-act="tutorial-next"]').click();
  await expect(page.locator('.tutorial-guide')).toContainText('Tu primera carta');
  await page.locator('.tactic:has([data-card-id="wave-push"])').first().click();
  await expect(page.locator('.selected-card-detail')).toBeVisible();
  await page.locator('.decision-dock [data-lane="TOP"]').click();
  await expect(page.locator('.tutorial-guide')).toContainText('La presión se convierte en daño');
  await page.locator('[data-act="pass"]').click();
  await expect(page.locator('.tutorial-done')).toBeVisible();
  await expect(page.locator('.lane.enemy[data-lane-column="TOP"] .tower')).not.toContainText('6/6');
  await page.locator('[data-act="tutorial-next"]').click();
  await expect(page.locator('.tutorial-guide')).toContainText('Una rotación táctica');
  await page.locator('.tactic:has([data-card-id="rotation"])').first().click();
  await page.locator('[data-unit="p0:c0"]').click();
  await page.locator('.decision-dock [data-lane="MID"]').click();
  await expect(page.locator('.tutorial-guide')).toContainText('Regresar a la base');
  await page.locator('[data-unit="p0:c1"]').click();
  await page.locator('[data-order="BACK"]').click();
  await expect(page.locator('.tutorial-guide')).toContainText('Vuelve a tu equipo');
  await page.locator('[data-act="pass"]').click();
  await expect(page.locator('.tutorial-guide')).toContainText('Vuelve a tu equipo');
  await page.locator('[data-act="pass"]').click();
  await expect(page.locator('.tutorial-done')).toBeVisible();
  await page.locator('[data-act="tutorial-next"]').click();
  await expect(page.locator('.tutorial-guide')).toContainText('Disputa el Latido');
  await expect(page.locator('[data-objective="minor"]')).toBeEnabled();
  await page.locator('.tactic:has([data-card-id="hunt"])').first().click();
  await page.locator('[data-objective="minor"]').click();
  await page.locator('.decision-dock [data-lane="MID"]').click();
  await expect(page.locator('.tutorial-guide')).toContainText('Confirma la conquista');
  await page.locator('[data-act="pass"]').click();
  await expect(page.locator('.tutorial-done')).toBeVisible();
  await expect(page.locator('.objective-tile[data-objective="minor"]')).toContainText('Azul');
  await page.locator('[data-act="tutorial-next"]').click();
  await expect(page.locator('.tutorial-guide')).toContainText('Un carril con brecha');
  await page.locator('.tactic:has([data-card-id="wave-push"])').first().click();
  await page.locator('.decision-dock [data-lane="TOP"]').click();
  await expect(page.locator('.tutorial-guide')).toContainText('Cierra la partida');
  await page.locator('[data-act="pass"]').click();
  await expect(page.locator('.tutorial-done')).toContainText('Abre camino al Nexo');
  await expect(page.locator('.result')).toContainText('Gana Azul');
  const keysAfter=await page.evaluate(()=>Object.keys(localStorage).sort());
  expect(keysAfter).toEqual(keysBefore);
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth);
  expect(overflow).toBeLessThanOrEqual(3);
  expect(errors).toEqual([]);
  await page.locator('[data-act="tutorial-next"]').click();
  await expect(page.getByText('Sorteo inicial')).toBeVisible();
  await context.close();
 });
}
test('tutorial can be replayed or exited without changing bot/hotseat rules',async({page})=>{
 await page.goto(base+'/card-game.html');
 await page.locator('[data-setup="tutorial"]').click();
 await page.locator('[data-act="tutorial-skip"]').click();
 await expect(page.locator('.tutorial-guide')).toContainText('Tu primera carta');
 await page.locator('[data-act="tutorial-exit"]').click();
 await expect(page.locator('.tutorial-guide')).toHaveCount(0);
 await page.locator('[data-setup="hotseat"]').click();
 await expect(page.getByText('Sorteo inicial')).toBeVisible();
});
