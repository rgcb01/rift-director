#!/usr/bin/env python3
"""Rebuild pilot masters/WebP and manifest from preserved native sources (Pillow)."""
import json
from pathlib import Path
from PIL import Image, ImageOps, ImageCms
ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / 'assets/card-art'
ALTS = {
 'hero-centinela': 'Centinela protege las murallas con un escudo de placas minerales entrelazadas por luz cian.',
 'hero-astral': 'Astral escucha las corrientes estelares suspendidas sobre su mano en un observatorio erosionado.',
 'hero-sombra': 'Sombra Errante avanza sigilosa entre rocas húmedas y grietas turquesa del Vínculo.',
 'great-convergence': 'Tres rutas de energía confluyen en una fortaleza y una onda dorada rompe la formación defensiva.',
 'disrupt': 'Una corriente de energía se curva y fragmenta alrededor de un obelisco agrietado.',
 'line-guard': 'Defensores resguardan una ruta bajo una barrera y escudos translúcidos de vidrio mineral.'
}
FOCAL = {'hero-centinela': (.5,.25), 'hero-astral': (.5,.35), 'hero-sombra': (.5,.3), 'great-convergence': (.5,.4), 'disrupt': (.5,.4), 'line-guard': (.5,.45)}
srgb = ImageCms.ImageCmsProfile(ImageCms.createProfile('sRGB')).tobytes()
manifest = {}
for id, alt in ALTS.items():
 source = BASE / 'sources' / (id + '.png')
 with Image.open(source) as original:
  native = original.size
  im = original.convert('RGB')
  if original.info.get('icc_profile'):
   import io
   im = ImageCms.profileToProfile(im, ImageCms.ImageCmsProfile(io.BytesIO(original.info['icc_profile'])), ImageCms.createProfile('sRGB'), outputMode='RGB')
  def save(folder, name, size, **options):
   path = BASE / folder / name
   path.parent.mkdir(parents=True, exist_ok=True)
   ImageOps.fit(im, size, method=Image.Resampling.LANCZOS).save(path, icc_profile=srgb, **options)
   return str(path.relative_to(ROOT))
  master = save('masters', id+'.png', (1536,2048), optimize=True)
  variants = {str(w): save('webp', f'{id}-{w}.webp', (w,w*4//3), quality=82, method=6) for w in (192,384,768)}
  manifest[id] = {'source': str(source.relative_to(ROOT)), 'sourceSize': list(native), 'master': master, 'masterSize': [1536,2048], 'variants': variants, 'focal': dict(zip(('x','y'),FOCAL[id])), 'alt': alt, 'generation': {'tool':'image_gen.imagegen','model':'not exposed by tool','date':'2026-11-24','promptVersion':'v092-pilot-1','promptFile':'assets/card-art/prompts.json','seed':None,'adaptation':'Proportional Lanczos resampling to 1536×2048; upscale adds no new detail. WebP derived directly from native source.'}}
(BASE / 'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
# Static module means a failed image request never blocks game initialization.
(BASE / 'manifest.mjs').write_text('// Generated by scripts/process-card-art.py; do not edit.\nexport const CARD_ART = '+json.dumps(manifest,ensure_ascii=False,indent=2)+';\n')
print('Built 6 masters, 18 WebP, JSON + module manifests from native sources.')
